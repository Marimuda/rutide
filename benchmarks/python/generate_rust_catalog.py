"""Generate the checked-in Rust constituent catalog from the pinned UTide oracle."""

from __future__ import annotations

import argparse
import hashlib
import math
from pathlib import Path
from typing import Any

import numpy as np

from rutide_baseline.constants import DEFAULT_UTIDE_ROOT, EXPECTED_UTIDE_REVISION, REPOSITORY_ROOT
from rutide_baseline.runner import load_oracle

DEFAULT_OUTPUT = REPOSITORY_ROOT / "crates/rutide-core/src/catalog_generated.rs"


def _float(value: Any) -> str:
    number = float(value)
    if not math.isfinite(number):
        raise ValueError(f"catalog value must be finite: {number}")
    rendered = repr(number)
    if "e" not in rendered and "." not in rendered:
        rendered += ".0"
    return rendered


def _optional_range(start: Any, length: Any) -> tuple[int, int]:
    if not np.isfinite(start):
        if np.isfinite(length):
            raise ValueError("catalog range has a length without a start")
        return 0, 0
    if not np.isfinite(length):
        raise ValueError("catalog range has a start without a length")
    return int(start) - 1, int(length)


def _doodson(values: Any) -> str:
    array = np.asarray(values, dtype=np.float64)
    if not np.isfinite(array).all():
        return "None"
    integers = [int(value) for value in array]
    if not np.array_equal(array, integers):
        raise ValueError(f"non-integral Doodson multipliers: {array}")
    return f"Some({integers!r})"


def render_catalog(utide_root: Path) -> str:
    """Return deterministic Rust source for the verified oracle checkout."""
    load_oracle(utide_root)
    from utide._ut_constants import ut_constants

    constants_path = utide_root / "utide/data/ut_constants.npz"
    source_sha256 = hashlib.sha256(constants_path.read_bytes()).hexdigest()
    constituent = ut_constants.const
    satellite = ut_constants.sat
    shallow = ut_constants.shallow

    if len(constituent.name) != 146 or len(satellite.iconst) != 162 or len(shallow.iconst) != 251:
        raise ValueError("pinned UTide catalog dimensions changed unexpectedly")

    lines = [
        "// @generated by benchmarks/python/generate_rust_catalog.py; do not edit.",
        f'pub(super) const ORACLE_REVISION: &str = "{EXPECTED_UTIDE_REVISION}";',
        f'pub(super) const SOURCE_SHA256: &str = "{source_sha256}";',
        "",
        "pub(super) const CATALOG: [CatalogEntry; 146] = [",
    ]
    for index, raw_name in enumerate(constituent.name):
        name = str(raw_name)
        satellite_start, satellite_len = _optional_range(
            constituent.isat[index], constituent.nsat[index]
        )
        shallow_start, shallow_len = _optional_range(
            constituent.ishallow[index], constituent.nshallow[index]
        )
        if not np.all(
            satellite.iconst[satellite_start : satellite_start + satellite_len] == index + 1
        ):
            raise ValueError(f"satellite range is inconsistent for {name}")
        if not np.all(shallow.iconst[shallow_start : shallow_start + shallow_len] == index + 1):
            raise ValueError(f"shallow range is inconsistent for {name}")
        semi = (
            f"Some({_float(constituent.semi[index])})"
            if np.isfinite(constituent.semi[index])
            else "None"
        )
        lines.extend(
            [
                "    CatalogEntry {",
                f'        name: "{name}",',
                f"        doodson: {_doodson(constituent.doodson[index])},",
                f"        semi: {semi},",
                f"        rayleigh_cph: {_float(constituent.df[index])},",
                f"        reference_frequency_cph: {_float(constituent.freq[index])},",
                f"        satellite_start: {satellite_start},",
                f"        satellite_len: {satellite_len},",
                f"        shallow_start: {shallow_start},",
                f"        shallow_len: {shallow_len},",
                "    },",
            ]
        )
    lines.extend(["];", "", "pub(super) const SATELLITES: [Satellite; 162] = ["])
    for index in range(len(satellite.iconst)):
        delta = [int(value) for value in satellite.deldood[index]]
        lines.extend(
            [
                "    Satellite {",
                f"        delta_doodson: {delta!r},",
                f"        phase_correction: {_float(satellite.phcorr[index])},",
                f"        amplitude_ratio: {_float(satellite.amprat[index])},",
                f"        latitude_factor: {int(satellite.ilatfac[index])},",
                "    },",
            ]
        )
    lines.extend(["];", "", "pub(super) const SHALLOW_TERMS: [ShallowTerm; 251] = ["])
    for index in range(len(shallow.iconst)):
        lines.extend(
            [
                "    ShallowTerm {",
                f"        parent_index: {int(shallow.iname[index]) - 1},",
                f"        coefficient: {_float(shallow.coef[index])},",
                "    },",
            ]
        )
    lines.extend(["];", ""])
    return "\n".join(lines)


def parse_args(arguments: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--utide-root", type=Path, default=DEFAULT_UTIDE_ROOT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args(arguments)


def main(arguments: list[str] | None = None) -> int:
    args = parse_args(arguments)
    rendered = render_catalog(args.utide_root.resolve(strict=True))
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != rendered:
            raise SystemExit(f"generated catalog is stale: {args.output}")
        print(f"generated catalog is current: {args.output}")
        return 0
    args.output.write_text(rendered, encoding="utf-8")
    print(f"wrote Rust catalog: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
